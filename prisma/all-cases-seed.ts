// All-cases dataset: one Project, "Test Nagar (All Cases)", told through one
// Member (Vijay Rathore) and one Customer (Rajat Malpani) whose two profiles
// carry every rule of the CRM. Lives beside the demo and never touches it.
//
//   npm run seed:all-cases
//
// Re-runnable: removes only its own Projects (ALLC, ALLR), People (mobiles
// 94000…), payment references (TUTR / TNEFT / TRFD) and Land Inquiries
// (ALLCASE-…) first. Writes docs/All_Cases_Guide.md.
import { writeFileSync } from "node:fs";
import { assertCheckDatabase } from "./check-guard.ts";
import { purgeScope } from "./check-cleanup.ts";
import { installStoryClock } from "./demo/story-clock.ts";

assertCheckDatabase();
installStoryClock();

const { db, people, projectIds, startNumbersAt } = await import("./demo/toolkit.ts");
const { CUSTOMERS, MEMBERS, PROJECTS } = await import("./demo/world.ts");
const { AC_CUSTOMERS, AC_LAND_PREFIX, AC_MEMBERS, AC_MOBILE_PREFIX, AC_PROJECT, AC_PROJECT_CODES, AC_REF_PREFIXES } = await import("./demo/all-cases-world.ts");
const { CASES, NOTES, tellAllCases } = await import("./demo/all-cases.ts");
const { runAllJobs } = await import("@/lib/jobs");

// The toolkit reads its cast and Projects from world.ts; this dataset adds its own.
Object.assign(MEMBERS, AC_MEMBERS);
Object.assign(CUSTOMERS, AC_CUSTOMERS);
PROJECTS[AC_PROJECT.code] = AC_PROJECT;
startNumbersAt(5000);

async function wipe() {
  await db.landInquiry.deleteMany({ where: { createRequestId: { startsWith: AC_LAND_PREFIX } } });
  const ids = (await db.project.findMany({ where: { projectCode: { in: AC_PROJECT_CODES } }, select: { id: true } })).map((p) => p.id);
  await purgeScope(db, {
    tag: null,
    bookings: { projectId: { in: ids } },
    persons: { primaryMobile: { startsWith: AC_MOBILE_PREFIX } },
    plots: { projectId: { in: ids } },
    projects: { id: { in: ids } },
    acquisitions: { OR: [{ plot: { projectId: { in: ids } } }, { resaleGroupId: { in: ids } }] },
    references: { OR: AC_REF_PREFIXES.map((p) => ({ normalisedKey: { startsWith: p } })) },
  });
}

async function writeGuide() {
  const rows = await db.person.findMany({
    where: { id: { in: Object.values(people).map((p) => p.id) } },
    select: { id: true, customerProfile: { select: { customerId: true } }, memberProfile: { select: { memberId: true, status: true } } },
  });
  const byId = new Map(rows.map((r) => [r.id, r]));
  const ids = (personId: string) => {
    const r = byId.get(personId);
    return [r?.memberProfile?.memberId, r?.customerProfile?.customerId].filter(Boolean).join(" / ") || "—";
  };
  const members = Object.keys(AC_MEMBERS).map((k) => people[k]).filter(Boolean);
  const customers = Object.keys(NOTES).filter((k) => !(k in AC_MEMBERS) && people[k]);
  const areas = [...new Set(CASES.map((c) => c.area))];
  const counts = {
    plots: await db.plot.count({ where: { projectId: projectIds[AC_PROJECT.code] } }),
    bookings: await db.booking.count({ where: { projectId: projectIds[AC_PROJECT.code] } }),
  };
  const lines = [
    "# All Cases Guide — Test Nagar",
    "",
    `Generated by \`npm run seed:all-cases\` on ${new Date().toISOString().slice(0, 10)}. One Project, **${AC_PROJECT.name}**, with ${counts.plots} Plots and ${counts.bookings} Bookings, made through the same services the screens use, dated between April and today.`,
    "",
    `Open two profiles: **${people.TM01.name}** (${ids(people.TM01.id)}) for every Member rule and **${people.HC.name}** (${ids(people.HC.id)}) for every Customer rule. States that cannot be true at once (RERA Expired and Registered, Active and Deactivated, a Recovery owed and repaid) happened one after another and show in their History.`,
    "",
    "Sign in as MD (STF-0001), Accounts (STF-0003 / STF-0004) or CRM (STF-0005). The demo Projects are untouched.",
    "",
    ...areas.flatMap((area) => [
      `## ${area}`,
      "",
      "| Plot | Case | Where to see it |",
      "|---|---|---|",
      ...CASES.filter((c) => c.area === area).map((c) => `| ${c.plot} | ${c.title} | ${c.see} |`),
      "",
    ]),
    "## Members",
    "",
    "| Name | Member ID | Case |",
    "|---|---|---|",
    ...members.map((m) => `| ${m.name} | ${ids(m.id)} | ${NOTES[m.key] ?? "—"} |`),
    "",
    "## Customers worth opening",
    "",
    "| Name | Customer ID | Case |",
    "|---|---|---|",
    ...customers.map((k) => `| ${people[k].name} | ${ids(people[k].id)} | ${NOTES[k]} |`),
    "",
    "Re-run `npm run seed:all-cases` to rebuild this Project from scratch.",
    "",
  ];
  writeFileSync("docs/All_Cases_Guide.md", lines.join("\n"), "utf-8");
}

try {
  await wipe();
  await tellAllCases();
  await runAllJobs(new Date()); // real time: old Holds lapse, overdue turns urgent, RERA and Trip reminders
  await writeGuide();
  console.log("seed:all-cases done — see docs/All_Cases_Guide.md");
} catch (error) {
  console.error(error);
  process.exitCode = 1;
} finally {
  await db.$disconnect();
}
